    /// <summary>
    /// Portable Marching Cubes isosurface extractor. Returns raw float arrays
    /// (positions, normals, indices) so the caller can upload to any GPU API
    /// (OpenGL, Vulkan, Metal) without a WPF dependency.
    /// </summary>
    public static class PortableMarchingCubes
    {
        /// <summary>
        /// Result of an isosurface extraction — flat arrays ready for GPU upload.
        /// Positions and normals are interleaved as [x,y,z, x,y,z, ...].
        /// </summary>
        public readonly struct IsosurfaceResult
        {
            public readonly float[] Positions;
            public readonly float[] Normals;
            public readonly int[] Indices;
            public readonly int VertexCount;
            public readonly int TriangleCount;

            public IsosurfaceResult(float[] positions, float[] normals, int[] indices)
            {
                Positions = positions;
                Normals = normals;
                Indices = indices;
                VertexCount = positions.Length / 3;
                TriangleCount = indices.Length / 3;
            }
        }

        /// <summary>
        /// Extract an isosurface from a 3D scalar field at the given threshold.
        /// </summary>
        /// <param name="field">3D scalar field [x, y, z].</param>
        /// <param name="isoValue">Concentration threshold.</param>
        /// <param name="originX">World X of grid corner [0,0,0].</param>
        /// <param name="originY">World Y of grid corner [0,0,0].</param>
        /// <param name="originZ">World Z of grid corner [0,0,0].</param>
        /// <param name="cellSizeX">Grid spacing in X.</param>
        /// <param name="cellSizeY">Grid spacing in Y.</param>
        /// <param name="cellSizeZ">Grid spacing in Z.</param>
        /// <returns>Mesh data, or null if the isosurface is empty.</returns>
        public static IsosurfaceResult? GenerateIsosurface(
            double[,,] field, double isoValue,
            double originX, double originY, double originZ,
            double cellSizeX, double cellSizeY, double cellSizeZ)
        {
            int nx = field.GetLength(0);
            int ny = field.GetLength(1);
            int nz = field.GetLength(2);

            var vertList = new float[12 * 3]; // 12 edge interpolation slots × 3 floats
            double snapRes = Math.Min(cellSizeX, Math.Min(cellSizeY, cellSizeZ)) * 0.001;
            var vertexMap = new Dictionary<long, int>();
            var positions = new List<float>();
            var normals = new List<float>();
            var indices = new List<int>();

            for (int i = 0; i < nx - 1; i++)
            {
                for (int j = 0; j < ny - 1; j++)
                {
                    for (int k = 0; k < nz - 1; k++)
                    {
                        double v0 = field[i, j, k];
                        double v1 = field[i + 1, j, k];
                        double v2 = field[i + 1, j + 1, k];
                        double v3 = field[i, j + 1, k];
                        double v4 = field[i, j, k + 1];
                        double v5 = field[i + 1, j, k + 1];
                        double v6 = field[i + 1, j + 1, k + 1];
                        double v7 = field[i, j + 1, k + 1];

                        int cubeIndex = 0;
                        if (v0 >= isoValue) cubeIndex |= 1;
                        if (v1 >= isoValue) cubeIndex |= 2;
                        if (v2 >= isoValue) cubeIndex |= 4;
                        if (v3 >= isoValue) cubeIndex |= 8;
                        if (v4 >= isoValue) cubeIndex |= 16;
                        if (v5 >= isoValue) cubeIndex |= 32;
                        if (v6 >= isoValue) cubeIndex |= 64;
                        if (v7 >= isoValue) cubeIndex |= 128;

                        if (EdgeTable[cubeIndex] == 0) continue;

                        float ox = (float)(originX + i * cellSizeX);
                        float oy = (float)(originY + j * cellSizeY);
                        float oz = (float)(originZ + k * cellSizeZ);
                        float cx = (float)cellSizeX, cy = (float)cellSizeY, cz = (float)cellSizeZ;

                        // 8 cube corner positions
                        float p0x = ox,      p0y = oy,      p0z = oz;
                        float p1x = ox + cx, p1y = oy,      p1z = oz;
                        float p2x = ox + cx, p2y = oy + cy, p2z = oz;
                        float p3x = ox,      p3y = oy + cy, p3z = oz;
                        float p4x = ox,      p4y = oy,      p4z = oz + cz;
                        float p5x = ox + cx, p5y = oy,      p5z = oz + cz;
                        float p6x = ox + cx, p6y = oy + cy, p6z = oz + cz;
                        float p7x = ox,      p7y = oy + cy, p7z = oz + cz;

                        int edges = EdgeTable[cubeIndex];
                        if ((edges &    1) != 0) Interp(vertList,  0, p0x,p0y,p0z, p1x,p1y,p1z, v0, v1, isoValue);
                        if ((edges &    2) != 0) Interp(vertList,  1, p1x,p1y,p1z, p2x,p2y,p2z, v1, v2, isoValue);
                        if ((edges &    4) != 0) Interp(vertList,  2, p2x,p2y,p2z, p3x,p3y,p3z, v2, v3, isoValue);
                        if ((edges &    8) != 0) Interp(vertList,  3, p3x,p3y,p3z, p0x,p0y,p0z, v3, v0, isoValue);
                        if ((edges &   16) != 0) Interp(vertList,  4, p4x,p4y,p4z, p5x,p5y,p5z, v4, v5, isoValue);
                        if ((edges &   32) != 0) Interp(vertList,  5, p5x,p5y,p5z, p6x,p6y,p6z, v5, v6, isoValue);
                        if ((edges &   64) != 0) Interp(vertList,  6, p6x,p6y,p6z, p7x,p7y,p7z, v6, v7, isoValue);
                        if ((edges &  128) != 0) Interp(vertList,  7, p7x,p7y,p7z, p4x,p4y,p4z, v7, v4, isoValue);
                        if ((edges &  256) != 0) Interp(vertList,  8, p0x,p0y,p0z, p4x,p4y,p4z, v0, v4, isoValue);
                        if ((edges &  512) != 0) Interp(vertList,  9, p1x,p1y,p1z, p5x,p5y,p5z, v1, v5, isoValue);
                        if ((edges & 1024) != 0) Interp(vertList, 10, p2x,p2y,p2z, p6x,p6y,p6z, v2, v6, isoValue);
                        if ((edges & 2048) != 0) Interp(vertList, 11, p3x,p3y,p3z, p7x,p7y,p7z, v3, v7, isoValue);

                        var tri = TriTable[cubeIndex];
                        for (int t = 0; tri[t] != -1; t += 3)
                        {
                            int ea = tri[t], eb = tri[t + 1], ec = tri[t + 2];
                            float ax = vertList[ea * 3], ay = vertList[ea * 3 + 1], az = vertList[ea * 3 + 2];
                            float bx = vertList[eb * 3], by = vertList[eb * 3 + 1], bz = vertList[eb * 3 + 2];
                            float cx2 = vertList[ec * 3], cy2 = vertList[ec * 3 + 1], cz2 = vertList[ec * 3 + 2];

                            // Face normal
                            float abx = bx - ax, aby = by - ay, abz = bz - az;
                            float acx = cx2 - ax, acy = cy2 - ay, acz = cz2 - az;
                            float nx2 = aby * acz - abz * acy;
                            float ny2 = abz * acx - abx * acz;
                            float nz2 = abx * acy - aby * acx;
                            float nl = MathF.Sqrt(nx2 * nx2 + ny2 * ny2 + nz2 * nz2);
                            if (nl > 1e-10f) { nx2 /= nl; ny2 /= nl; nz2 /= nl; }

                            int ia = GetOrAddVertex(ax, ay, az, snapRes, vertexMap, positions, normals);
                            int ib = GetOrAddVertex(bx, by, bz, snapRes, vertexMap, positions, normals);
                            int ic = GetOrAddVertex(cx2, cy2, cz2, snapRes, vertexMap, positions, normals);

                            // Accumulate normals for smooth shading
                            normals[ia * 3] += nx2; normals[ia * 3 + 1] += ny2; normals[ia * 3 + 2] += nz2;
                            normals[ib * 3] += nx2; normals[ib * 3 + 1] += ny2; normals[ib * 3 + 2] += nz2;
                            normals[ic * 3] += nx2; normals[ic * 3 + 1] += ny2; normals[ic * 3 + 2] += nz2;

                            indices.Add(ia);
                            indices.Add(ib);
                            indices.Add(ic);
                        }
                    }
                }
            }

            if (positions.Count == 0) return null;

            // Normalize accumulated normals
            var normArr = normals.ToArray();
            for (int n = 0; n < normArr.Length; n += 3)
            {
                float len = MathF.Sqrt(
                    normArr[n] * normArr[n] +
                    normArr[n + 1] * normArr[n + 1] +
                    normArr[n + 2] * normArr[n + 2]);
                if (len > 1e-10f)
                {
                    normArr[n] /= len;
                    normArr[n + 1] /= len;
                    normArr[n + 2] /= len;
                }
            }

            return new IsosurfaceResult(positions.ToArray(), normArr, indices.ToArray());
        }

        private static void Interp(float[] vertList, int slot,
            float p1x, float p1y, float p1z,
            float p2x, float p2y, float p2z,
            double v1, double v2, double iso)
        {
            float t;
            if (Math.Abs(v2 - v1) < 1e-12)
                t = 0.5f;
            else
                t = (float)((iso - v1) / (v2 - v1));

            int b = slot * 3;
            vertList[b]     = p1x + t * (p2x - p1x);
            vertList[b + 1] = p1y + t * (p2y - p1y);
            vertList[b + 2] = p1z + t * (p2z - p1z);
        }

        private static int GetOrAddVertex(float px, float py, float pz,
            double snapRes, Dictionary<long, int> map,
            List<float> positions, List<float> normals)
        {
            long kx = (long)Math.Round(px / snapRes);
            long ky = (long)Math.Round(py / snapRes);
            long kz = (long)Math.Round(pz / snapRes);
            long key = kx * 1000000007L + ky * 1000000009L + kz;

            if (map.TryGetValue(key, out int idx))
                return idx;

            idx = positions.Count / 3;
            map[key] = idx;
            positions.Add(px);
            positions.Add(py);
            positions.Add(pz);
            normals.Add(0f);
            normals.Add(0f);
            normals.Add(0f);
            return idx;
        }

