    /// <summary>
    /// Implements the Marching Cubes algorithm for extracting isosurfaces from a 3D scalar field.
    /// </summary>
    public static class MarchingCubes
    {
        /// <summary>
        /// Extracts an isosurface mesh from a 3D scalar field at the specified iso-value.
        /// </summary>
        /// <param name="field">3D array of scalar values.</param>
        /// <param name="isoValue">The concentration threshold defining the isosurface.</param>
        /// <param name="origin">World-space origin of the grid (corner at index [0,0,0]).</param>
        /// <param name="cellSize">Spacing between grid points in world units.</param>
        /// <returns>A <see cref="MeshGeometry3D"/> representing the isosurface with shared vertices and averaged normals.</returns>
        public static MeshGeometry3D GenerateIsosurface(
            double[,,] field, double isoValue, Point3D origin, double cellSize)
        {
            var mesh = new MeshGeometry3D();
            int nx = field.GetLength(0);
            int ny = field.GetLength(1);
            int nz = field.GetLength(2);

            var vertList = new Point3D[12];
            double snapRes = cellSize * 0.001;
            var vertexMap = new Dictionary<long, int>();
            var positions = new List<Point3D>();
            var normals = new List<Vector3D>();
            var indices = new List<int>();

            for (int i = 0; i < nx - 1; i++)
            {
                for (int j = 0; j < ny - 1; j++)
                {
                    for (int k = 0; k < nz - 1; k++)
                    {
                        double v0 = field[i, j, k];
                        double v1 = field[i + 1, j, k];
                        double v2 = field[i + 1, j + 1, k];
                        double v3 = field[i, j + 1, k];
                        double v4 = field[i, j, k + 1];
                        double v5 = field[i + 1, j, k + 1];
                        double v6 = field[i + 1, j + 1, k + 1];
                        double v7 = field[i, j + 1, k + 1];

                        int cubeIndex = 0;
                        if (v0 >= isoValue) cubeIndex |= 1;
                        if (v1 >= isoValue) cubeIndex |= 2;
                        if (v2 >= isoValue) cubeIndex |= 4;
                        if (v3 >= isoValue) cubeIndex |= 8;
                        if (v4 >= isoValue) cubeIndex |= 16;
                        if (v5 >= isoValue) cubeIndex |= 32;
                        if (v6 >= isoValue) cubeIndex |= 64;
                        if (v7 >= isoValue) cubeIndex |= 128;

                        if (EdgeTable[cubeIndex] == 0) continue;

                        double ox = origin.X + i * cellSize;
                        double oy = origin.Y + j * cellSize;
                        double oz = origin.Z + k * cellSize;

                        var p0 = new Point3D(ox, oy, oz);
                        var p1 = new Point3D(ox + cellSize, oy, oz);
                        var p2 = new Point3D(ox + cellSize, oy + cellSize, oz);
                        var p3 = new Point3D(ox, oy + cellSize, oz);
                        var p4 = new Point3D(ox, oy, oz + cellSize);
                        var p5 = new Point3D(ox + cellSize, oy, oz + cellSize);
                        var p6 = new Point3D(ox + cellSize, oy + cellSize, oz + cellSize);
                        var p7 = new Point3D(ox, oy + cellSize, oz + cellSize);

                        int edges = EdgeTable[cubeIndex];
                        if ((edges & 1) != 0) vertList[0] = Interpolate(p0, p1, v0, v1, isoValue);
                        if ((edges & 2) != 0) vertList[1] = Interpolate(p1, p2, v1, v2, isoValue);
                        if ((edges & 4) != 0) vertList[2] = Interpolate(p2, p3, v2, v3, isoValue);
                        if ((edges & 8) != 0) vertList[3] = Interpolate(p3, p0, v3, v0, isoValue);
                        if ((edges & 16) != 0) vertList[4] = Interpolate(p4, p5, v4, v5, isoValue);
                        if ((edges & 32) != 0) vertList[5] = Interpolate(p5, p6, v5, v6, isoValue);
                        if ((edges & 64) != 0) vertList[6] = Interpolate(p6, p7, v6, v7, isoValue);
                        if ((edges & 128) != 0) vertList[7] = Interpolate(p7, p4, v7, v4, isoValue);
                        if ((edges & 256) != 0) vertList[8] = Interpolate(p0, p4, v0, v4, isoValue);
                        if ((edges & 512) != 0) vertList[9] = Interpolate(p1, p5, v1, v5, isoValue);
                        if ((edges & 1024) != 0) vertList[10] = Interpolate(p2, p6, v2, v6, isoValue);
                        if ((edges & 2048) != 0) vertList[11] = Interpolate(p3, p7, v3, v7, isoValue);

                        for (int t = 0; TriTable[cubeIndex][t] != -1; t += 3)
                        {
                            var a = vertList[TriTable[cubeIndex][t]];
                            var b = vertList[TriTable[cubeIndex][t + 1]];
                            var c = vertList[TriTable[cubeIndex][t + 2]];

                            var faceNormal = Vector3D.CrossProduct(b - a, c - a);
                            if (faceNormal.LengthSquared > 1e-20)
                                faceNormal.Normalize();

                            int ia = GetOrAddVertex(a, snapRes, vertexMap, positions, normals);
                            int ib = GetOrAddVertex(b, snapRes, vertexMap, positions, normals);
                            int ic = GetOrAddVertex(c, snapRes, vertexMap, positions, normals);

                            normals[ia] += faceNormal;
                            normals[ib] += faceNormal;
                            normals[ic] += faceNormal;

                            indices.Add(ia);
                            indices.Add(ib);
                            indices.Add(ic);
                        }
                    }
                }
            }

            foreach (var pos in positions)
                mesh.Positions.Add(pos);

            for (int n = 0; n < normals.Count; n++)
            {
                var norm = normals[n];
                if (norm.LengthSquared > 1e-20)
                    norm.Normalize();
                mesh.Normals.Add(norm);
            }

            foreach (var idx in indices)
                mesh.TriangleIndices.Add(idx);

            return mesh;
        }

        private static int GetOrAddVertex(Point3D p, double snapRes,
            Dictionary<long, int> map, List<Point3D> positions, List<Vector3D> normals)
        {
            long kx = (long)System.Math.Round(p.X / snapRes);
            long ky = (long)System.Math.Round(p.Y / snapRes);
            long kz = (long)System.Math.Round(p.Z / snapRes);
            long key = kx * 1000000007L + ky * 1000000009L + kz;

            int idx;
            if (map.TryGetValue(key, out idx))
                return idx;

            idx = positions.Count;
            map[key] = idx;
            positions.Add(p);
            normals.Add(new Vector3D(0, 0, 0));
            return idx;
        }

        private static Point3D Interpolate(Point3D p1, Point3D p2, double v1, double v2, double iso)
        {
            if (System.Math.Abs(v2 - v1) < 1e-12)
                return new Point3D((p1.X + p2.X) * 0.5, (p1.Y + p2.Y) * 0.5, (p1.Z + p2.Z) * 0.5);

            double t = (iso - v1) / (v2 - v1);
            return new Point3D(
                p1.X + t * (p2.X - p1.X),
                p1.Y + t * (p2.Y - p1.Y),
                p1.Z + t * (p2.Z - p1.Z));
        }

